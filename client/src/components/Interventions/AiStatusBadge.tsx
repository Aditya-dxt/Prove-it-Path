import React from 'react';
import { SparklesIcon } from '../Common/Icons';

interface AiStatusBadgeProps {
  source: 'ai' | 'template';
  fallbackUsed?: boolean;
}

export const AiStatusBadge: React.FC<AiStatusBadgeProps> = ({ source, fallbackUsed }) => {
  const isAi = source === 'ai' && !fallbackUsed;

  return (
    <div
      style={{
        display: 'inline-flex',
        alignItems: 'center',
        gap: '0.35rem',
        padding: '0.2rem 0.55rem',
        borderRadius: 'var(--radius-sm)',
        fontSize: '0.75rem',
        fontWeight: 600,
        backgroundColor: isAi ? '#f2eefa' : 'var(--bg-surface-subtle)',
        color: isAi ? '#5b32a3' : 'var(--text-muted)',
        border: `1px solid ${isAi ? '#dcd2f3' : 'var(--border-light)'}`,
        letterSpacing: '0.02em',
        userSelect: 'none'
      }}
      title={
        isAi
          ? 'Explanation generated dynamically by AI backend'
          : 'Explanation generated by deterministic curriculum template (standard fallback)'
      }
    >
      {isAi ? <SparklesIcon size={12} color="#5b32a3" /> : <span>&para;</span>}
      <span>{isAi ? 'AI Explanation' : 'Template Explanation'}</span>
    </div>
  );
};
